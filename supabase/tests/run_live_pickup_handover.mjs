function cli(args) {
  const escaped = args.map((value) => {
    const text = String(value);
    assert.equal(text.includes(secret ?? '\u0000'), false, 'Admin credential must not enter CLI arguments');
    return `"${text.replaceAll('"', '\\"')}"`;
  });
  const command = `npx --offline --yes supabase@2.122.0 ${escaped.join(' ')}`;
  try {
    return execSync(command, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 5e6,
      timeout: 60000,
    });
  } catch {
    throw new Error('Supabase CLI operation failed; credential-bearing output suppressed');
  }
}

