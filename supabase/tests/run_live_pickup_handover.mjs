function stateSnapshotSql(taskId) {
  return `select
    (select row_to_json(t) from public.delivery_tasks t where t.id='${taskId}') as task,
    (select row_to_json(r) from public.return_requests r where r.id='${ids.returnRequest}') as return_request,
    (select jsonb_agg(to_jsonb(i) order by i.id) from public.return_items i
      where i.return_request_id='${ids.returnRequest}') as return_items,
    (select jsonb_agg(to_jsonb(v) order by v.id) from public.product_variants v
      where v.id in ('${ids.variantA}','${ids.variantB}')) as inventory,
    (select jsonb_agg(to_jsonb(m) order by m.id) from public.inventory_movements m
      where m.order_id='${ids.order}' or m.return_request_id='${ids.returnRequest}') as inventory_movements,
    (select row_to_json(c) from public.cod_collections c where c.order_id='${ids.order}') as cod,
    (select count(*)::integer from public.delivery_attempts a where a.order_id='${ids.order}') as delivery_attempts;`;
}

async function spawnUi(shipper, taskId, redelivery = false) {
  const childEnv = {
    ...process.env,
    LIVE_PICKUP_HANDOVER_UI: '1',
    LIVE_SUPABASE_URL: config.SUPABASE_URL,
    LIVE_PUBLISHABLE_KEY: config.SUPABASE_PUBLISHABLE_KEY,
    LIVE_TEST_EMAIL: shipper.email,
    LIVE_TEST_PASSWORD: shipper.password,
    LIVE_TASK_ID: taskId,
    LIVE_REDELIVERY_UI: redelivery ? '1' : '0',
    LIVE_REDELIVERY_FAILURE: failRedelivery ? '1' : '0',
  };
  const exitCode = await new Promise((resolveExit, reject) => {
    const child = spawn(
      'flutter',
      ['test', '--no-pub', redelivery ? 'test/live/live_redelivery_ui_test.dart' : 'test/live/live_pickup_handover_ui_test.dart'],
      {
        cwd: root,
        env: childEnv,
        shell: process.platform === 'win32',
        stdio: ['ignore', 'pipe', 'pipe'],
      },
    );
    const redact = (value) => {
      let output = value.toString();
      for (const user of users) output = output.replaceAll(user.password, '[redacted]');
      output = output.replaceAll(secret, '[redacted]');
      return output;
    };
    child.stdout.on('data', (value) => process.stdout.write(redact(value)));
    child.stderr.on('data', (value) => process.stderr.write(redact(value)));
    child.on('error', reject);
    child.on('close', resolveExit);
  });
  assert.equal(exitCode, 0, 'Live pickup handover Flutter UI test failed');
}

