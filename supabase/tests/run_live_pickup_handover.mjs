function inside(parent, child) {
  const parentPath = resolve(parent);
  const childPath = resolve(child);
  const suffix = relative(parentPath, childPath);
  return suffix !== '' && !suffix.startsWith('..') && !isAbsolute(suffix);
}

function parseCliRows(output) {
  const result = JSON.parse(output);
  return result.rows ?? result;
}

async function query(sql) {
  // SQL generated by this runner contains only UUIDs and fixed fixture text.
  // This assertion prevents a future edit from accidentally writing the Admin
  // key into the bridge or temporary query file.
  assert.equal(sql.includes(secret), false, 'Admin credential must not enter fixture SQL');
  if (bridgeRoot) {
    assert.ok(inside(sqlRoot, bridgeRoot), 'SQL bridge must stay in supabase/.temp');
    await mkdir(bridgeRoot, { recursive: true });
    const id = randomUUID();
    const request = resolve(bridgeRoot, 'request.json');
    const response = resolve(bridgeRoot, `response-${id}.json`);
    await writeFile(request, JSON.stringify({ id, sql }));
    console.log('LIVE SQL bridge: pending scoped query');
    try {
      for (let attempt = 0; attempt < 1200; attempt += 1) {
        let result;
        try {
          result = JSON.parse(await readFile(response, 'utf8'));
        } catch (error) {
          if (error.code !== 'ENOENT') throw error;
        }
        if (result) {
          await unlink(response).catch(() => {});
          await unlink(request).catch(() => {});
          assert.ok(!result.error, 'Connected SQL tool rejected scoped query');
          return result.rows ?? result;
        }
        await delay(100);
      }
    } finally {
      await unlink(request).catch(() => {});
    }
    throw new Error('Connected SQL handoff timed out');
  }
  await mkdir(sqlRoot, { recursive: true });
  await writeFile(sqlFile, sql);
  try {
    return parseCliRows(cli(['db', 'query', '--linked', '--file', sqlFile]));
  } finally {
    await unlink(sqlFile).catch(() => {});
  }
}

async function admin(path, method, body) {
  const response = await fetch(`${config.SUPABASE_URL}/auth/v1/admin/${path}`, {
    method,
    headers: {
      apikey: secret,
      Authorization: `Bearer ${secret}`,
      'Content-Type': 'application/json',
    },
    body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(20000),
  });
  if (method === 'DELETE' && response.status === 404) return null;
  assert.ok(response.ok, `Auth Admin ${method} failed (${response.status}); response suppressed`);
  return response.status === 204 ? null : response.json();
}

async function login(user) {
  const response = await fetch(
    `${config.SUPABASE_URL}/auth/v1/token?grant_type=password`,
    {
      method: 'POST',
      headers: {
        apikey: config.SUPABASE_PUBLISHABLE_KEY,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ email: user.email, password: user.password }),
      signal: AbortSignal.timeout(20000),
    },
  );
  assert.ok(response.ok, `Real password login failed (${response.status})`);
  return (await response.json()).access_token;
}

async function rawRpc(token, name, body) {
  const response = await fetch(`${config.SUPABASE_URL}/rest/v1/rpc/${name}`, {
    method: 'POST',
    headers: {
      apikey: config.SUPABASE_PUBLISHABLE_KEY,
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(body),
    signal: AbortSignal.timeout(20000),
  });
  let data = null;
  try {
    data = await response.json();
  } catch {
    // Keep denial diagnostics generic; never print a response containing a
    // token or any other credential if a proxy returns unexpected content.
  }
  return { response, data };
}

async function rpc(token, name, body) {
  const { response, data } = await rawRpc(token, name, body);
  assert.ok(response.ok, `${name} failed HTTP ${response.status} / ${data?.code ?? 'unknown'}`);
  return data;
}

async function expectRpcError(token, name, body, code, message) {
  const { response, data } = await rawRpc(token, name, body);
  assert.equal(response.ok, false, `${name} unexpectedly authorized`);
  assert.equal(data?.code, code, `${name} denial code mismatch`);
  if (message) assert.equal(data?.message, message, `${name} denial marker mismatch`);
}

